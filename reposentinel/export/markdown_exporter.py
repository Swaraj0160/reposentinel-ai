"""Markdown report exporter for RepoSentinel AI."""

from datetime import datetime, timezone
from reposentinel.core.config import APP_NAME, VERSION
from reposentinel.core.models import ScanReport


def export_report_to_markdown(report: ScanReport) -> str:
    """Exports a ScanReport model into a clean GitHub-Flavored Markdown report."""
    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

    lines = [
        f"# {APP_NAME} Security Audit Report",
        "",
        f"- **Project:** `{report.project_name}`",
        f"- **Audit Date:** `{timestamp}`",
        f"- **Engine Version:** `{VERSION}`",
        f"- **Files Scanned:** `{report.files_scanned}`",
        f"- **Hardcoded Secret Findings:** `{len(report.secret_findings)}`",
        f"- **Dependency Advisories:** `{len(report.dependency_advisories)}`",
        f"- **Parsed Dependencies:** `{len(report.dependencies_parsed)}`",
        "",
        "---",
        "",
        "## 1. Executive Summary",
        "",
    ]

    critical_count = sum(1 for s in report.secret_findings if s.severity == "Critical") + sum(1 for a in report.dependency_advisories if a.severity == "Critical")
    high_count = sum(1 for s in report.secret_findings if s.severity == "High") + sum(1 for a in report.dependency_advisories if a.severity == "High")
    medium_count = sum(1 for s in report.secret_findings if s.severity == "Medium") + sum(1 for a in report.dependency_advisories if a.severity == "Medium")

    lines.extend([
        f"| Severity Level | Count |",
        f"| :--- | :--- |",
        f"| 🚨 Critical | {critical_count} |",
        f"| ⚠️ High | {high_count} |",
        f"| 🟡 Medium | {medium_count} |",
        "",
        "> [!NOTE]",
        "> Security findings represent static heuristic detections and public vulnerability advisories. ",
        "> Findings are signals for triage and require developer verification.",
        "",
    ])

    # Secrets section
    lines.extend(["## 2. Hardcoded Secret Findings", ""])
    if report.secret_findings:
        for idx, sec in enumerate(report.secret_findings, start=1):
            badge = "🚨" if sec.severity == "Critical" else ("⚠️" if sec.severity == "High" else "🟡")
            lines.extend([
                f"### {idx}. {badge} [{sec.severity}] {sec.rule}",
                f"- **Location:** `{sec.file}:{sec.line}`",
                f"- **Evidence (Redacted):** `{sec.evidence}`",
                f"- **Remediation:** {sec.recommendation}",
                "",
            ])
    else:
        lines.extend(["*No potential secrets detected by active heuristic scanner rules.*", ""])

    # Dependencies section
    lines.extend(["## 3. Dependency Vulnerability Advisories", ""])
    if report.dependency_advisories:
        for idx, adv in enumerate(report.dependency_advisories, start=1):
            badge = "🚨" if adv.severity == "Critical" else ("⚠️" if adv.severity == "High" else "🟡")
            fix_str = f"`{adv.fixed_version}`" if adv.fixed_version else "*No direct fix reported in advisory*"
            lines.extend([
                f"### {idx}. {badge} {adv.package} ({adv.version}) — {adv.id}",
                f"- **Ecosystem:** `{adv.ecosystem}` | **Severity:** `{adv.severity}`",
                f"- **Recommended Fixed Version:** {fix_str}",
                f"- **Summary:** {adv.summary}",
                f"- **Advisory Reference:** [{adv.url}]({adv.url})",
                "",
            ])
    else:
        lines.extend(["*No public advisories matched parsed project dependencies.*", ""])

    # AI Triage section
    if report.ai_triage:
        lines.extend([
            "## 4. AI-Assisted Security Triage & Remediation Plan",
            "",
            report.ai_triage,
            "",
        ])

    # Verified Remediation section
    if report.verification_results:
        lines.extend(["## 5. Verified Remediation Results", ""])
        for v in report.verification_results:
            icon = "✅" if v.status == "VERIFIED" else ("❌" if v.status == "FAILED" else "ℹ️")
            lines.extend([
                f"- **{icon} [{v.status}] {v.file}** ({v.finding_id})",
                f"  - {v.summary}",
                "",
            ])

    lines.extend([
        "---",
        f"*Report generated by [{APP_NAME}](https://github.com/reposentinel-ai/reposentinel).* "
        "Deterministic scanners & OSV database are open-source. Review changes before merging.",
    ])

    return "\n".join(lines)
